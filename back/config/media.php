<?php

declare(strict_types=1);

return [

    /*
    |--------------------------------------------------------------------------
    | Картинки: пересборка в WebP
    |--------------------------------------------------------------------------
    |
    | Всё, что загружают как изображение — аватарка, обложка курса, значок
    | достижения, вложение урока, новости, документа и переписки, — ложится в
    | хранилище одним форматом. Снимок с телефона весит мегабайты и приезжает
    | в ленту как есть; WebP при том же изображении занимает втрое-впятеро
    | меньше, а читателю не видно разницы.
    |
    | Выключается целиком: без обработчика файлы кладутся как приходят.
    |
    */

    'webp' => [

        'enabled' => (bool) env('MEDIA_WEBP', true),

        /*
         * Качество кодирования, 0–100.
         *
         * 82 — обычная граница, ниже которой на фотографии начинает быть
         * заметна «каша» по краям контрастных деталей. Выше 90 файл растёт
         * заметно, а глаз разницы уже не берёт.
         */
        'quality' => (int) env('MEDIA_WEBP_QUALITY', 82),

        /*
         * Во сколько пикселей упирается длинная сторона.
         *
         * Главная экономия не в формате, а здесь: камера телефона снимает
         * 4000 точек в ширину, а самое широкое место в приложении — около
         * 1200, и на экране с удвоенной плотностью этого хватает с запасом.
         * Меньше исходника не растягиваем — увеличенная картинка хуже, чем
         * маленькая.
         */
        'max_side' => (int) env('MEDIA_WEBP_MAX_SIDE', 2560),

        /*
         * Сколько точек соглашаемся разжать в память.
         *
         * GD держит картинку несжатой, по четыре байта на точку: тридцать
         * мегапикселей — это сто двадцать мегабайт сверх всего остального.
         * Что больше, кладётся как пришло: уронить загрузку хуже, чем
         * сохранить тяжёлый файл.
         */
        'max_pixels' => (int) env('MEDIA_WEBP_MAX_PIXELS', 30_000_000),
    ],

];
