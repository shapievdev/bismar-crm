<?php

declare(strict_types=1);

return [

    /*
    |--------------------------------------------------------------------------
    | Подключение к ClickHouse
    |--------------------------------------------------------------------------
    |
    | Этот файл заменяет собой конфиг пакета `glushkovds/phpclickhouse-laravel`,
    | который иначе подставился бы целиком. Заменяется он ровно из-за двух
    | значений ниже — `readonly` и `settings`; остальное повторяет пакетные
    | значения по умолчанию с нашими таймаутами и базой.
    |
    | Соединение описано здесь, а не в `config/database.php`: пакет сам
    | регистрирует подключение `clickhouse` из ключа `clickhouse.connection`,
    | а запись в `database.connections.clickhouse` только перекрывает его
    | поверх. Держать настройку в двух местах незачем.
    |
    */

    'connection' => [

        'driver' => 'clickhouse',

        'host' => env('CLICKHOUSE_HOST', '127.0.0.1'),

        'port' => (int) env('CLICKHOUSE_PORT', 8123),

        'database' => env('CLICKHOUSE_DATABASE', 'mart'),

        'username' => env('CLICKHOUSE_USERNAME', 'default'),

        'password' => env('CLICKHOUSE_PASSWORD', ''),

        'https' => (bool) env('CLICKHOUSE_HTTPS', false),

        /*
        |----------------------------------------------------------------------
        | Чей сертификат считать своим
        |----------------------------------------------------------------------
        |
        | Путь к корневому сертификату — для случая, когда у сервера аналитики
        | сертификат самоподписанный. Публичного удостоверяющего центра для
        | адреса во внутренней сети не бывает, а curl без доверенного корня
        | такое соединение просто разорвёт.
        |
        | Пусто — проверка идёт по системным корням: так и нужно, когда
        | сертификат выписан на доменное имя обычным центром.
        |
        | Ключ назван `sslCA`, а не по-нашему: его читает сам клиент
        | (ClickHouseDB\Client::__construct), и переименованный он просто не
        | будет замечен. Отсутствующий путь клиент не применяет — поэтому
        | незаполненная переменная ничего не меняет.
        |
        */

        'sslCA' => env('CLICKHOUSE_SSL_CA') ?: null,

        /*
        |----------------------------------------------------------------------
        | Проверять ли, с кем мы вообще соединились
        |----------------------------------------------------------------------
        |
        | Клиент по умолчанию не проверяет сертификат сервера совсем:
        | `CurlerRequest` выставляет `SSL_VERIFYPEER => false` и
        | `SSL_VERIFYHOST => 0`. На «https» это даёт шифрование и ничего
        | больше — подменивший ответ посередине пройдёт незамеченным, а
        | посередине в нашем случае целый интернет: сервер аналитики стоит в
        | офисной сети, боевой сайт у хостера.
        |
        | Поэтому при `https` проверка включается обратно — и подлинности
        | сертификата, и имени, на которое он выписан. Сертификат обязан быть
        | выписан ровно на то, что стоит в `CLICKHOUSE_HOST`: на доменное имя,
        | если соединяемся по имени, и с `subjectAltName=IP:…`, если по адресу.
        |
        | Выключатель оставлен на случай разбирательства, но выключенная
        | проверка — это «https», который защищает только от подслушивания.
        |
        */

        'curl_options' => (bool) env('CLICKHOUSE_HTTPS', false) && (bool) env('CLICKHOUSE_SSL_VERIFY', true)
            ? [
                CURLOPT_SSL_VERIFYPEER => true,
                CURLOPT_SSL_VERIFYHOST => 2,
            ]
            : [],

        /*
        | Таймауты сторожат дашборд, а не сервер: запрос по двум миллионам
        | строк идёт секунды, а вот недоступный сервер в локальной сети не
        | должен держать страницу до упора.
        */

        'timeout_connect' => (int) env('CLICKHOUSE_TIMEOUT_CONNECT', 5),

        'timeout_query' => (int) env('CLICKHOUSE_TIMEOUT_QUERY', 30),

        'retries' => (int) env('CLICKHOUSE_RETRIES', 0),

        /*
        |----------------------------------------------------------------------
        | Пользователь с правами только на чтение
        |----------------------------------------------------------------------
        |
        | Флаг говорит не «запрещать запись нам», а «на той стороне читатель».
        | У `reader` в профиле ClickHouse стоит `readonly = 1`, и это запрещает
        | менять в запросе любую настройку. Клиент же без этого флага сам
        | добавляет к каждому SELECT `readonly = 2`, а к нему ещё и
        | `max_execution_time` — сервер отвечает `Code: 164 READONLY`, и
        | аналитика целиком превращается в «сервер недоступен». С флагом клиент
        | эти параметры из запроса убирает.
        |
        | Снимается вместе с ними и `max_execution_time`, так что предел
        | ожидания остаётся только наш — `timeout_query` выше.
        |
        */

        'readonly' => true,

        /*
        | Пусто намеренно. Пакет по умолчанию кладёт сюда
        | `max_partitions_per_insert_block` — настройку для вставок, которых у
        | читателя не бывает, — и получает тот же отказ `READONLY`. Любая
        | настройка, добавленная здесь, уйдёт в каждый запрос и упрётся в то же
        | самое: менять их `reader` не вправе.
        */

        'settings' => [],

        'fix_default_query_builder' => true,

    ],

];
