<?php

declare(strict_types=1);

return [

    /*
    |--------------------------------------------------------------------------
    | Подключение и база
    |--------------------------------------------------------------------------
    |
    | Аналитика читает ClickHouse — отдельный сервер, который наполняет выгрузка
    | из 1С. Права там только на чтение, и большего слою ниже не нужно.
    |
    | Читается витринный слой `mart`, а не сырой `raw`. Разница не в удобстве:
    | в сырых данных розница лежит двумя потоками сразу, себестоимость
    | проставлена у трёх четвертей строк, а клиент не отличим от разового
    | покупателя. Витрина всё это уже свела — прибыль в ней достоверна (выручки
    | без себестоимости около четырёх процентов против двадцати четырёх),
    | возвраты сопоставлены с основаниями, а поздние корректировки себестоимости
    | приведены к той же строке регистра.
    |
    | Разметку клиентов витрина не отдаёт, и RFM, когорты и LTV считаются
    | запросом по всей её истории (см. `Mart`). ABC/XYZ она считает сама, но
    | отдельной таблицей-снимком, а не в строке продажи.
    |
    | Имя базы подставляется в SQL, а не передаётся параметром: ClickHouse не
    | принимает имя таблицы через плейсхолдер. Поэтому значение обязано
    | оставаться настройкой администратора и никогда не приходить от
    | пользователя — см. ClickHouse::qualify().
    |
    */

    'connection' => env('ANALYTICS_CONNECTION', 'clickhouse'),

    'database' => env('ANALYTICS_DATABASE', 'mart'),

    /*
    |--------------------------------------------------------------------------
    | Кэш
    |--------------------------------------------------------------------------
    |
    | Витрина пересобирается ночью, поэтому в течение дня один и тот же вопрос
    | даёт один и тот же ответ. Пять минут — компромисс: панель на пяти запросах
    | по двум миллионам строк не должна пересчитываться на каждое нажатие
    | вкладки, но и «вчерашних» цифр на экране в рабочий день быть не должно.
    |
    | Ключ строится из имени отчёта и всех фильтров, поэтому смена периода или
    | склада гарантированно даёт свой ответ, а не чужой из кэша.
    |
    */

    'cache_ttl' => (int) env('ANALYTICS_CACHE_TTL', 300),

    /*
    |--------------------------------------------------------------------------
    | Размеры выдачи
    |--------------------------------------------------------------------------
    |
    | Сколько строк возвращают рейтинги. Предел стоит на сервере, а не на
    | клиенте: 29 тысяч артикулов и 15 тысяч клиентов в ответе не нужны никому,
    | а браузер на них ляжет.
    |
    */

    'top_limit' => (int) env('ANALYTICS_TOP_LIMIT', 15),

    'max_top_limit' => (int) env('ANALYTICS_MAX_TOP_LIMIT', 100),

    /*
    |--------------------------------------------------------------------------
    | Пауза, после которой клиент считается вернувшимся
    |--------------------------------------------------------------------------
    |
    | Полгода — не «давно не покупал», а «перестал покупать и передумал». Для
    | строительных материалов это разумный срок: сезон кончился, объект сдали,
    | следующий начался. Магазину с недельным циклом покупки здесь нужно другое
    | число, поэтому оно настройка, а не константа в запросе.
    |
    */

    'pause_days' => (int) env('ANALYTICS_PAUSE_DAYS', 180),

    /*
    |--------------------------------------------------------------------------
    | Пороги RFM
    |--------------------------------------------------------------------------
    |
    | Прошлая витрина размечала клиентов сама; нынешняя отдаёт только продажи,
    | и сегмент считается запросом — по давности покупки с одной стороны и
    | ценности клиента с другой (см. Mart::rfm()).
    |
    | Числа заданы порогами, а не квантилями, и это осознанно. Квантиль
    | подстраивается под выбранный фильтр: тот же клиент оказался бы «лучшим» в
    | срезе одного склада и «постоянным» в срезе всей сети, а сегмент обязан
    | означать одно и то же в любом разрезе. Значения ниже взяты по
    | распределению витрины — медиана давности около ста дней, три четверти
    | клиентов делают до двадцати заказов, — и подлежат правке, когда торговля
    | изменится.
    |
    */

    'rfm' => [

        // Давность последней покупки.
        'fresh_days' => (int) env('ANALYTICS_RFM_FRESH_DAYS', 30),
        'warm_days' => (int) env('ANALYTICS_RFM_WARM_DAYS', 120),
        'cold_days' => (int) env('ANALYTICS_RFM_COLD_DAYS', 365),

        // Сколько клиент считается новым со своей первой покупки.
        'newcomer_days' => (int) env('ANALYTICS_RFM_NEWCOMER_DAYS', 90),

        // Частота: заказов за всю историю.
        'frequent_orders' => (int) env('ANALYTICS_RFM_FREQUENT_ORDERS', 20),
        'regular_orders' => (int) env('ANALYTICS_RFM_REGULAR_ORDERS', 7),

        // Деньги: выручка за всю историю, рубли.
        'large_money' => (int) env('ANALYTICS_RFM_LARGE_MONEY', 135000),
        'medium_money' => (int) env('ANALYTICS_RFM_MEDIUM_MONEY', 50000),

    ],

];