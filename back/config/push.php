<?php

declare(strict_types=1);

return [

    /*
    |--------------------------------------------------------------------------
    | Ключи VAPID
    |--------------------------------------------------------------------------
    |
    | Пара, которой служба доставки браузера (у Google, Apple и Mozilla она
    | своя) узнаёт наш сервер: приватным подписывается каждая отправка,
    | публичный отдаётся браузеру в момент подписки и навсегда привязывает её к
    | этой паре. Сменив ключи, вы разом отвяжете все подписки.
    |
    | Пустые ключи — рабочий случай: приложение живёт без уведомлений, и
    | отправка тихо ничего не делает, вместо того чтобы падать на каждом
    | сообщении в мессенджере.
    |
    | `subject` — контакт для самой службы доставки: `mailto:` или адрес сайта.
    |
    */

    'vapid' => [
        'subject' => env('VAPID_SUBJECT', env('APP_FRONTEND_URL', 'http://localhost:3100')),
        'public_key' => env('VAPID_PUBLIC_KEY'),
        'private_key' => env('VAPID_PRIVATE_KEY'),
    ],

    /*
    |--------------------------------------------------------------------------
    | Сколько уведомление ждёт человека
    |--------------------------------------------------------------------------
    |
    | Телефон бывает выключен; служба доставки придержит уведомление столько
    | секунд и выбросит. Сутки: сообщение недельной давности, вывалившееся при
    | включении, — уже не новость, а недоумение.
    |
    */

    'ttl' => (int) env('PUSH_TTL', 86400),

];
