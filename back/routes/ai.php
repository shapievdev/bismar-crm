<?php

declare(strict_types=1);

use App\Http\Middleware\EnsureEmployed;
use App\Mcp\Servers\Bismar;
use Illuminate\Support\Facades\Route;
use Laravel\Mcp\Facades\Mcp;
use Laravel\Mcp\Server\Registrar;
use Laravel\Passport\Http\Middleware\CheckToken;

/*
|--------------------------------------------------------------------------
| Коннектор claude.ai
|--------------------------------------------------------------------------
|
| Один адрес для работы и несколько — чтобы коннектор нашёл, у кого спросить
| разрешение. Маршруты этого файла пакет грузит без группы `web`: ни сессии, ни
| проверки CSRF, и это ровно то, что нужно клиенту с токеном.
|
*/

/*
 * Как коннектору узнать, куда идти за разрешением.
 *
 * Три открытых адреса: описание защищаемого ресурса (RFC 9728), описание
 * сервера авторизации (RFC 8414) и регистрация клиента (RFC 7591). Первые два
 * отдают в точности то, что коннектор прочитает в заголовке `WWW-Authenticate`
 * нашего же отказа 401, и у вложенного описания `resource` равен
 * `https://crm.bismar.pro/mcp` — тому самому адресу, который сотрудник вводит в
 * claude.ai. Не совпади они, коннектор откажется подключаться.
 *
 * Ограничение по частоте — потому что регистрация открыта без входа: так
 * устроена динамическая регистрация, и это не оплошность, а способ подключить
 * клиента, которого мы не заводили руками. Куда такому клиенту позволено
 * возвращаться, решает config/mcp.php, и там разрешены только домены Anthropic
 * — без этого открытый адрес регистрации был бы дверью без замка.
 */
Route::middleware('throttle:30,1')->group(static fn () => Mcp::oauthRoutes());

/*
 * Сам сервер.
 *
 * Три проверки на входе, и каждая отвечает на свой вопрос. `auth:api` — кто
 * пришёл: токен, выданный Passport, и человек, которому он выдан (удалённого
 * провайдер не найдёт — мягкое удаление снимает его со всех запросов).
 * `CheckToken` — за чем пришёл: у токена должно быть полномочие `mcp:use`, то
 * самое, которое сотрудник подтвердил на экране согласия. `EnsureEmployed` —
 * работает ли он ещё: увольнение гасит выданные токены, но проверка стоит и
 * здесь, потому что полагаться на уборку значило бы держать дверь открытой
 * ровно настолько, насколько повезёт.
 *
 * Что человеку можно делать — спрашивается не здесь, а в каждом инструменте, и
 * теми же правами, какими закрыт соответствующий адрес HTTP-API (см.
 * App\Mcp\Tools\BismarTool).
 *
 * Ограничение по частоте щедрее, чем у регистрации: модель задаёт по нескольку
 * вопросов на одну просьбу человека, и упираться в отказ посреди разговора она
 * не должна.
 */
Mcp::web('/mcp', Bismar::class)->middleware([
    'throttle:120,1',
    'auth:api',
    CheckToken::using(Registrar::OAUTH_SCOPE),
    EnsureEmployed::class,
]);
