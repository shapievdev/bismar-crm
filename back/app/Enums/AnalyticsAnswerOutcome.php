<?php

declare(strict_types=1);

namespace App\Enums;

/**
 * Чем кончился вопрос к ИИ-аналитику.
 *
 * Три исхода, и различать их нужно именно затем, чтобы знать, что чинить.
 * «Ответил словами» — обычное дело, а не неудача: половина вопросов к аналитике
 * панелью не отвечается. А вот если словами он отвечает всегда, значит модель не
 * справляется со словарём — и дело в подсказке, а не в сотрудниках.
 */
enum AnalyticsAnswerOutcome: string
{
    /** Ответил словами и собрал дашборд. */
    case Composed = 'composed';

    /** Ответил словами, панели не собрал. */
    case Explained = 'explained';

    /**
     * Не ответил вовсе: модель недоступна, вернула бессмыслицу или отказала.
     *
     * Такие записи не попадают ни в переписку на экране, ни в память модели: на
     * месте ответа у них сообщение о сбое, и подавать его модели как её
     * собственные прошлые слова значит учить её отвечать сообщениями об ошибках.
     */
    case Failed = 'failed';

    public function isUsable(): bool
    {
        return $this !== self::Failed;
    }
}
