<?php

declare(strict_types=1);

namespace App\Enums;

/**
 * У кого удаляют переписку.
 *
 * Два разных дела под одним словом «удалить». У себя — переписка уходит из
 * своего списка, у собеседника и в базе остаётся всё. У всех — разговора больше
 * нет ни у кого, вместе с сообщениями и приложенными файлами.
 */
enum DeletionScope: string
{
    case Mine = 'mine';

    case Everyone = 'everyone';
}
