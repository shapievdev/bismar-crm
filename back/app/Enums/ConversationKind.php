<?php

declare(strict_types=1);

namespace App\Enums;

/**
 * Личная переписка, групповая или общая на всю компанию.
 *
 * Различаются они немногим: у личной состав неизменен и имя берётся у
 * собеседника, у групповой есть название, владелец и люди, которых добавляют и
 * убирают. Всё остальное — лента, непрочитанное, вложения — общее.
 *
 * Общая — та же группа, но без владельца и без состава: в ней вся компания,
 * и состав ведёт не человек, а приложение (см. App\Support\Chat\GeneralChat).
 * Поэтому она отдельный вид, а не группа с особым названием: «нельзя выйти» и
 * «нельзя убрать участника» должны держаться на виде записи, а не на том,
 * вспомнит ли кто-нибудь проверить заголовок.
 *
 * Уведомления — переписка с приложением: в ней один человек, и говорит в ней
 * только оно само. Лента, непрочитанное и поиск у неё общие со всеми
 * остальными — отличается она ровно тем, что в ней нет поля ввода.
 */
enum ConversationKind: string
{
    case Direct = 'direct';

    case Group = 'group';

    case General = 'general';

    case System = 'system';

    /**
     * Многоголосая: со своим названием, без собеседника.
     *
     * Общая отвечает «да» вместе с групповой — всюду, где это спрашивают,
     * речь о том, чьё имя показать в заголовке и есть ли у разговора второй
     * участник, а не о том, кто им владеет.
     */
    public function isGroup(): bool
    {
        return $this !== self::Direct;
    }

    public function isGeneral(): bool
    {
        return $this === self::General;
    }

    /** Личные уведомления: в них пишет приложение, а не люди. */
    public function isSystem(): bool
    {
        return $this === self::System;
    }
}
