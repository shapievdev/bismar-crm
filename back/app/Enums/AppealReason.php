<?php

declare(strict_types=1);

namespace App\Enums;

/**
 * С чем сотрудник пришёл к автору материала.
 *
 * Две причины, и они разные по последствиям: «не хватило» значит дописать,
 * «написано неверно» — исправить. Свести их в одно «есть замечание» значит
 * заставить автора выяснять это перепиской, а разговор об этом начинается
 * ровно с этого вопроса.
 *
 * Третьей кнопки — «да, вопрос закрыт» — здесь нет намеренно: она никуда не
 * пишет и никого не беспокоит, а просто убирает панель (решение пользователя
 * 2026-09-06).
 */
enum AppealReason: string
{
    case Missing = 'missing';

    case Incorrect = 'incorrect';

    /** Подпись на карточке — та же, что и на кнопке, с которой всё началось. */
    public function label(): string
    {
        return match ($this) {
            self::Missing => 'Ответа не хватило',
            self::Incorrect => 'Здесь написано неверно',
        };
    }
}
