<?php

declare(strict_types=1);

namespace App\Enums;

/**
 * Чем закончился вопрос к консультанту.
 *
 * Ради этого различения журнал и заводится. «Не ответил» — это три разные
 * поломки, и чинятся они в разных местах: одна дописыванием материала, другая
 * настройкой поиска, третья сменой модели. Без такого деления список неудач
 * говорит только то, что что-то не работает.
 */
enum ConsultantOutcome: string
{
    /** Ответ построен и опирается на материал. */
    case Answered = 'answered';

    /**
     * Вопрос совпал со строкой таблицы, ответ отдан дословно.
     *
     * Отдельно от «ответил», потому что модель при этом не вызывалась вовсе:
     * иначе даровые попадания неотличимы от платных, и по журналу нельзя
     * судить о расходе.
     */
    case Verbatim = 'verbatim';

    /** Поиск не нашёл ничего — материала нет либо он назван другими словами. */
    case NothingFound = 'nothing-found';

    /**
     * Ответа не нашлось, но сотруднику показали материал по соседству.
     *
     * Отдельно от «не найдено», хотя дыра в базе та же: для сотрудника исход
     * другой — он ушёл не с пустыми руками, — а для автора это подсказка, где
     * дописывать. Тема в базе есть, разобранного вопроса в ней нет.
     */
    case Suggested = 'suggested';

    /** Поиск что-то отдал, но ответ не сослался ни на один фрагмент. */
    case Unused = 'unused';

    /** Модель не ответила: недоступна, не тот ключ, кончился лимит. */
    case Failed = 'failed';

    public function label(): string
    {
        return match ($this) {
            self::Answered => 'Ответил',
            self::Verbatim => 'Готовый ответ',
            self::NothingFound => 'Материал не найден',
            self::Suggested => 'Показано близкое',
            self::Unused => 'Материал не использован',
            self::Failed => 'Сбой модели',
        };
    }

    /** Что делать с таким вопросом — подсказка тому, кто разбирает журнал. */
    public function hint(): string
    {
        return match ($this) {
            self::Answered => 'Ответ опирается на материал базы.',
            self::Verbatim => 'Вопрос совпал со строкой таблицы урока — отдан готовый ответ автора, без обращения к модели.',
            self::NothingFound => 'Либо такого материала нет, либо он написан другими словами — допишите урок.',
            self::Suggested => 'Тема в базе есть, разобранного вопроса в ней нет: сотруднику показали соседний материал. Откройте вопрос — по нему видно, в какой урок просится ответ.',
            self::Unused => 'Фрагменты модели передали, а ответ ни на один не сослался. Откройте вопрос: если среди найденного есть подходящий урок — дело в модели, если нет — материала по теме нет.',
            self::Failed => 'Проверьте ключ, адрес и лимиты в настройках консультанта.',
        };
    }

    /**
     * @return list<array{value: string, label: string}>
     */
    public static function options(): array
    {
        return array_map(
            static fn (self $case): array => ['value' => $case->value, 'label' => $case->label()],
            self::cases(),
        );
    }
}
