<?php

declare(strict_types=1);

namespace App\Enums;

/**
 * Чем консультант ответил: курируемой таблицей или нарезкой текста.
 *
 * Записывается в журнал ради одной цифры — какая доля вопросов ещё держится на
 * запасном пути. Это и есть мера того, насколько таблицы уроков заполнены: пока
 * доля высока, авторам есть что размечать.
 */
enum AnswerPath: string
{
    /** Строка таблицы урока — вопрос и ответ, написанные автором. */
    case Curated = 'curated';

    /** Кусок текста урока, найденный поиском. */
    case Passages = 'passages';

    /**
     * Прямого ответа не нашлось — показан материал по соседству.
     *
     * Для журнала это не ответ, а пробел: сотруднику назвали, где искать
     * дальше, но написанного ответа на его вопрос в базе нет.
     */
    case Related = 'related';

    public function label(): string
    {
        return match ($this) {
            self::Curated => 'Таблица урока',
            self::Passages => 'Текст урока',
            self::Related => 'Близкий материал',
        };
    }
}
