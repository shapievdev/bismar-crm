<?php

declare(strict_types=1);

namespace App\Enums;

/**
 * Сказанное человеком или отмеченное системой.
 *
 * Системные — «Иванов добавил Петрова», «Сидоров вышел». Они идут той же лентой
 * и в том же порядке, потому что читаются вместе с разговором: понять, почему
 * в группе вдруг появился новый голос, иначе неоткуда.
 *
 * Текст у них записан готовым, а не собирается при чтении из имён участников:
 * человек мог с тех пор смениться, уволиться или переименоваться, а сказано
 * было то, что сказано.
 */
enum MessageKind: string
{
    case Text = 'text';

    case System = 'system';
}
