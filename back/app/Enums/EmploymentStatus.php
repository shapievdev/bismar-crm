<?php

declare(strict_types=1);

namespace App\Enums;

/**
 * В каком положении человек числится.
 *
 * Четыре случая, но хранятся в колонке только три: «уволен» выводится из даты
 * увольнения и в базу словом не пишется. Иначе одно и то же было бы сказано
 * дважды — датой и строкой, — а на дату смотрит половина приложения, от списка
 * коллег до мессенджера; разойдись они, и человек оказался бы уволенным в
 * отчёте и работающим везде остальном.
 *
 * Декрет и ВРИО — не увольнение: такие люди числятся в штате, входят в
 * численность и в систему тоже входят. Отличать их нужно затем, чтобы
 * руководитель видел, кто сейчас на месте, а текучесть не считала ушедшей ту,
 * что вернётся.
 */
enum EmploymentStatus: string
{
    case Working = 'working';

    case ParentalLeave = 'parental-leave';

    /** Исполняет обязанности — временно, пока не назначен постоянный. */
    case Acting = 'acting';

    /**
     * Ушёл. В колонке не встречается: это положение вычисляется по дате
     * увольнения — см. User::employmentStatus().
     */
    case Dismissed = 'dismissed';

    public function label(): string
    {
        return match ($this) {
            self::Working => 'Работает',
            self::ParentalLeave => 'В декрете',
            self::Acting => 'ВРИО',
            self::Dismissed => 'Уволен',
        };
    }

    /** Числится ли человек в штате: декрет и ВРИО — числятся. */
    public function isEmployed(): bool
    {
        return $this !== self::Dismissed;
    }

    /**
     * Что можно выставить рукой.
     *
     * Увольнение делается своим действием — с проверкой прав, обрывом сессий и
     * причиной ухода, — а не выбором из списка положений.
     *
     * @return list<self>
     */
    public static function assignable(): array
    {
        return [self::Working, self::ParentalLeave, self::Acting];
    }
}
