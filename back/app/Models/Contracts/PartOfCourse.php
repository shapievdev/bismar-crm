<?php

declare(strict_types=1);

namespace App\Models\Contracts;

use App\Models\Course;

/**
 * Запись, которая существует только внутри курса.
 *
 * Модуль, урок, приложенный файл, расшифровка — всё это части материала, и
 * доступ к ним решается доступом к курсу, а не отдельно. Интерфейс нужен, чтобы
 * спросить об этом, не разбирая по одному, что именно связал маршрут: этим и
 * занят EnsureCourseAccess.
 */
interface PartOfCourse
{
    /**
     * Курс, частью которого эта запись является.
     *
     * Null означает «курса больше нет» — материал мог остаться от мягко
     * удалённого курса. Для доступа это тот же отказ.
     */
    public function owningCourse(): ?Course;
}
