<?php

declare(strict_types=1);

namespace App\Models\Contracts;

/**
 * Материал, который согласуют перед публикацией: документ, справочник, курс.
 *
 * Устройство круга от материала не зависит (см. App\Models\MaterialReview), а
 * разного между ними ровно три вещи, и каждая — про сам материал, а не про
 * согласование: чем для него оборачивается «выложить», как он называется в
 * уведомлении и куда ведёт ссылка. Поэтому отвечает на них сам материал, а не
 * действие с развилкой по классу — такая развилка однажды забыла бы четвёртый
 * вид.
 */
interface Approvable
{
    /**
     * Выложить материал — то самое, что делает согласие всех.
     *
     * Вызывается уже внутри транзакции круга: либо материал выходит и круг
     * закрывается согласованным, либо не происходит ни того, ни другого.
     */
    public function publishAfterApproval(): void;

    /** Опубликован ли он сейчас: у отправленного на согласование бывает и так. */
    public function isPublished(): bool;

    /** Как назвать его в уведомлении и в очереди согласующего. */
    public function approvalTitle(): string;

    /** Куда идти смотреть — путь внутри приложения. */
    public function approvalPath(): string;

    /**
     * Чем он называется на экране: «документ», «справочник», «курс».
     *
     * Строкой для человека, а не именем класса: «Курс отправлен на
     * согласование» читают люди.
     */
    public function approvalLabel(): string;
}
