<?php

declare(strict_types=1);

namespace App\Models\Contracts;

use App\Models\Regulation;

/**
 * Запись, которая существует только внутри документа.
 *
 * Прежде у документа частей не было вовсе — он сам себе урок. С проверкой при
 * документе появилась первая: попытка её сдачи. Доступ к ней решается доступом
 * к самому документу, а не отдельно, — этим и занят EnsureCourseAccess.
 */
interface PartOfRegulation
{
    /**
     * Документ, частью которого эта запись является.
     *
     * Null означает «эта запись не документная» — так отвечает попытка теста
     * при уроке; её доступ решает курс. Тот же null отдаёт и часть мягко
     * удалённого документа: читать его больше нельзя.
     */
    public function owningRegulation(): ?Regulation;
}
