<?php

declare(strict_types=1);

namespace App\Support\Ai;

/**
 * Источник, взятый из нарезки текста, — куска урока или куска документа.
 *
 * От прочих источников (строки таблицы «вопрос — ответ») отличается тем, что за
 * ним стоит кусок расшифровки с посчитанным вектором. Смысловой пересортировке
 * нужен именно он: она сравнивает вектор вопроса с вектором куска.
 *
 * Ради этого одного метода интерфейс и заведён. Обойтись `Source` нельзя —
 * готовый ответ автора куском не подкреплён, — а перечислять оба класса через
 * `|` значит переписывать перечисление всякий раз, когда в базе появится третий
 * род материала.
 */
interface Excerpt extends Source
{
    /**
     * Номер куска расшифровки, из которого взят текст.
     *
     * Методом, а не свойством: свойство в договоре не выразить, а притворяться,
     * что оно есть, — значит однажды получить ошибку там, где её не ждут.
     */
    public function segment(): int;
}
