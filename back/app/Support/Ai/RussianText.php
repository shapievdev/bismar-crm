<?php

declare(strict_types=1);

namespace App\Support\Ai;

/**
 * Как текст готовится к русскому полнотекстовому поиску.
 *
 * Одно определение на всех: выражение, которым ищут, обязано совпасть с тем,
 * на котором построен индекс, иначе Postgres индекс просто не возьмёт. Пока
 * потребителей было двое — поиск и его миграция, — константы жили копиями;
 * с появлением третьего расхождение стало вопросом времени.
 */
final readonly class RussianText
{
    /**
     * Текст, приведённый к виду, который русский словарь способен прочесть.
     *
     * База создана в коллации C, где Postgres классифицирует только ASCII:
     * заглавная кириллица не сворачивается, поэтому «Что» никогда не совпадает
     * со списком стоп-слов и не доходит до стеммера, а типографские кавычки
     * вокруг «дорого» читаются как часть слова, а не как пунктуация. И то и
     * другое оставляет леммы, которым не с чем совпасть. Сворачивание через
     * ICU-коллацию и выброс кавычек, которых парсер не видит, это чинят.
     *
     * Применяется к каждому куску текста по обе стороны поиска — снимите с
     * одной из них, и они перестанут делить общий словарь.
     */
    private const NORMALISED = <<<'SQL'
        lower(regexp_replace(coalesce(%s, ''), '[«»„“”‘’‚‛…—–]', ' ', 'g') COLLATE "und-x-icu")
    SQL;

    /**
     * Два поля с разным весом: то, что называет предмет, весит больше того, где
     * он лишь упомянут.
     */
    private const DOCUMENT = <<<'SQL'
        setweight(to_tsvector('russian', %1$s), 'A')
        || setweight(to_tsvector('russian', %2$s), 'B')
    SQL;

    /** Текст, ставший искомым: колонка или `?` для самого вопроса. */
    public static function normalised(string $expression): string
    {
        return sprintf(self::NORMALISED, $expression);
    }

    /**
     * Документ из двух колонок, старшая первой.
     *
     * Колонки подставляются в выражение, а не связываются как значения, —
     * это часть определения индекса, а не пользовательский ввод. Вызывать
     * только с именами колонок, известными в коде.
     */
    public static function document(string $major, string $minor): string
    {
        return sprintf(
            self::DOCUMENT,
            self::normalised($major),
            self::normalised($minor),
        );
    }
}
