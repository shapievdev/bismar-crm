<?php

declare(strict_types=1);

namespace App\Support\Ai;

/**
 * Кусок материала, который консультанту позволено цитировать.
 *
 * Их два вида — строка таблицы урока и кусок его текста, — и различать их
 * должен только поиск. Дальше, где ответ собирается и где сверяются ссылки,
 * важно лишь то, что источник умеет назвать себя модели и читателю.
 */
interface Source
{
    /**
     * Как источник подаётся модели.
     *
     * Нумеруется местом в списке, а не собственным идентификатором: увидев
     * настоящие номера записей, модель пишет «источник 2» про второй показанный
     * ей кусок — ссылку на существующий урок, которого ей не давали, и которую
     * вызывающему остаётся только выбросить.
     */
    public function toPrompt(int $number): string;

    /**
     * Устойчивое имя источника.
     *
     * По нему повторные ссылки схлопываются в одну. Именно источника, а не
     * урока: два куска одного урока — два разных места, и склеив их, под
     * утверждением окажется цитата из другого.
     */
    public function key(): string;

    /** Как источник показывается читателю. */
    public function citation(): Citation;
}
