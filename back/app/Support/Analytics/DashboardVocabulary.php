/**
 * Словарь, которым ИИ-аналитик говорит о цифрах.
 *
 * Главный класс всей затеи, и его назначение двойное: он же уходит модели
 * подсказкой, он же проверяет её ответ. Отсюда и правило, которое нельзя
 * нарушать: **у словаря одна копия**. Разойдись подсказка с проверкой — и
 * модель уверенно предложит показатель, который приложение не умеет считать.
 *
 * Почему словарь, а не схема базы. Модели было бы проще рассказать, какие в
 * ClickHouse таблицы и столбцы, и дать ей писать запросы самой. Так нельзя, и
 * причин две.
 *
 * Первая: цифры этой компании стоят на правилах, которых в столбцах нет.
 * Анонимная розница не считается клиентом, но только в разрезе клиентов;
 * возвраты вычитаются из выручки, а не лежат отдельной графой; у части выручки
 * витрина не знает себестоимости, и маржа по ней приблизительна. Модель,
 * считающая сама, всё это потеряет — и в компании появятся две разные «выручки
 * за сентябрь», обе убедительные и несходящиеся. Здесь же показатели называются
 * ровно теми именами, под которыми их считает App\Support\Analytics\SalesReport
 * и соседние отчёты, то есть то же самое, что показано на вкладках.
 *
 * Вторая: диск ClickHouse занят почти целиком, а в витрине сотни миллионов
 * строк. Один неудачный запрос модели останавливает аналитику всем, кто её в
 * этот момент открыл.
 *
 * Что отсюда следует для читателя: добавляя показатель или разрез в отчёт,
 * добавьте его здесь — иначе ИИ-аналитик о нём не узнает. А выдумав его здесь,
 * не забудьте, что исполнитель (DashboardExecutor) обязан уметь его посчитать:
 * на этом стоит проверка в DashboardSpec.
 */
