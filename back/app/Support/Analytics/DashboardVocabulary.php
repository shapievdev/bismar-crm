    /**
     * По какое число доехала витрина — или null, если спросить не у кого.
     *
     * Нужна исполнителю: срез, заходящий за эту дату, кончается неполными
     * днями, и сказать об этом надо цифрой, а не намёком.
     */
    public function lastLoadedDate(): ?string
    {
        $values = $this->filters();

        foreach ($values['freshness'] ?? [] as $source) {
            // Пустая строка — это «не знаем», а не дата: витрина отвечает так,
            // когда в ней за этот источник ещё ничего нет. Сказать «данные
            // доехали по » было бы хуже, чем промолчать.
            $date = is_array($source) ? trim((string) ($source['last_date'] ?? '')) : '';

            if ($date !== '') {
                return $date;
            }
        }

        return null;
    }

