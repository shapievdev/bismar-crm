    /**
     * Словарь в том виде, в каком его читает модель.
     *
     * Текстом, а не JSON: подсказка — это объяснение, и перечисление с
     * пояснением «когда это уместно» модель понимает лучше, чем схему. Схема
     * нужна в другом месте — в требованиях к ответу (см. DashboardSpec).
     */
    public function forPrompt(): string
    {
        $metrics = [];

        foreach ($this->metrics() as $key => $meta) {
            $metrics[] = "- `{$key}` — {$meta['label']}".(isset($meta['hint']) ? '. '.$meta['hint'] : '.');
        }

        $dimensions = [];

        foreach ($this->dimensions() as $key => $meta) {
            $dimensions[] = "- `{$key}` — {$meta['label']}.";
        }

        $widgets = [];

        foreach ($this->widgets() as $key => $meta) {
            $widgets[] = "- `{$key}` — {$meta['label']}. {$meta['when']}";
        }

        $caveats = [];

        foreach ($this->caveats() as $index => $caveat) {
            $caveats[] = ($index + 1).'. '.$caveat;
        }

        $periods = implode(', ', Period::presets());
        $values = $this->filters();

        $filters = ($values['unavailable'] ?? false) === true
            ? 'Сейчас недоступны — сервер аналитики не ответил. Не отбирай ни по складам, ни по каналам: '
                .'названий ты не знаешь, а выдуманное даст пустую панель.'
            : (string) json_encode($values, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);

        return <<<TEXT
        # Показатели

        {$this->lines($metrics)}

        # Разрезы

        {$this->lines($dimensions)}

        # Виды панелей

        {$this->lines($widgets)}

        # Периоды

        Готовые: {$periods}. Или произвольный — `from` и `to` как ГГГГ-ММ-ДД.
        Шаг графика: day, week, month; без него выбирается по длине периода.

        # Чем можно отобрать и по какое число доехали данные

        {$filters}

        # Что обязательно знать об этих цифрах

        {$this->lines($caveats)}
        TEXT;
    }

    /**
     * @param  list<string>  $lines
     */
    private function lines(array $lines): string
    {
        return implode("\n", $lines);
    }
}
