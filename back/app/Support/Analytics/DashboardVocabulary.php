     * панель, которую не отличить от «не продавали».
     *
     * Сюда же — по какое число доехали данные. Без этого «ноль за сегодня»
     * читалось бы как провал в торговле, а не как незагруженная выгрузка.
     *
     * Недоступная витрина это место не роняет, и это не мелочь: ClickHouse
     * стоит на сервере компании и доезжает туннелем, а словарь нужен ещё до
     * того, как модель что-нибудь попросит. Отвались он здесь — и ИИ-аналитик
     * перестал бы отвечать даже словами, хотя для слов витрина не нужна.
     * Значений в таком случае нет, и модели сказано об этом прямо: пусть
     * обойдётся без отбора, а не выдумывает названия складов.
     *
     * @return array<string, mixed>
     */
