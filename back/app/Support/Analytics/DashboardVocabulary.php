    /**
     * Словарь в том виде, в каком его читает модель.
     *
     * Текстом, а не JSON: подсказка — это объяснение, и перечисление с
     * пояснением «когда это уместно» модель понимает лучше, чем схему. Схема
     * нужна в другом месте — в требованиях к ответу (см. DashboardSpec).
     */
    public function forPrompt(): string
    {
        $metrics = [];

        foreach ($this->metrics() as $key => $meta) {
            $where = implode(', ', $meta['in']);

            $metrics[] = "- `{$key}` — {$meta['label']}. Годится в: {$where}."
                .(isset($meta['hint']) ? ' '.$meta['hint'] : '');
        }

        $dimensions = [];

        foreach ($this->dimensions() as $key => $meta) {
            $dimensions[] = "- `{$key}` — {$meta['label']}.";
        }

        $widgets = [];

        foreach ($this->widgets() as $key => $meta) {
            $widgets[] = "- `{$key}` — {$meta['label']}. {$meta['when']}";
        }

        $caveats = [];

        foreach ($this->caveats() as $index => $caveat) {
            $caveats[] = ($index + 1).'. '.$caveat;
        }

        $today = CarbonImmutable::today();
        $yesterday = $today->subDay()->toDateString();
        $before = $today->subDays(2)->toDateString();
        $thisMonth = $today->translatedFormat('F Y');
        $lastMonth = $today->subMonth()->translatedFormat('F Y');
        $today = $today->toDateString();

        return <<<TEXT
        # Показатели

        {$this->lines($metrics)}

        # Разрезы

        {$this->lines($dimensions)}

        # Виды панелей

        {$this->lines($widgets)}

        # Какое сегодня число

        Сегодня — {$today}. Вчера — {$yesterday}. Позавчера — {$before}.
        Текущий месяц — {$thisMonth}, прошлый — {$lastMonth}.

        # Периоды

        Готовые пресеты означают «последние N дней, считая сегодняшний», и ничего
        больше:

        - `today` — сегодня;
        - `week` — последние 7 дней;
        - `month` — последние 30 дней;
        - `quarter` — последние 90 дней, он же «три месяца»;
        - `half-year` — последние 180 дней;
        - `year` — последние 365 дней;
        - `two-years` — последние 730 дней.

        **Названный день или названный месяц пресетом не выражается.** Как только
        в вопросе есть «вчера», «в августе», «за сентябрь», «с 1 по 15 числа» —
        ставь `from` и `to` как ГГГГ-ММ-ДД и пресет не посылай вовсе:

        - «вчера» → `"from": "{$yesterday}", "to": "{$yesterday}"`;
        - «за август 2026» → `"from": "2026-08-01", "to": "2026-08-31"`;
        - «за прошлый месяц» → первое и последнее число месяца {$lastMonth};
        - «с 1 по 15 сентября» → `"from": "2026-09-01", "to": "2026-09-15"`.

        Ошибиться тут нельзя: заголовок у панели твой, а период считает приложение
        по `slice`. Назовёшь в словах август, а в `slice` оставишь пресет — человек
        увидит заголовок «август» над цифрами за последние тридцать дней.

        Шаг графика: day, week, month. Без него он выбирается по длине периода, и
        это хороший выбор — называй шаг только тогда, когда о нём спросили.

        # Чем можно отобрать и по какое число доехали данные

        Отбор кладётся в `slice`: `channels`, `warehouses`, `segments`, `departments` —
        каждый списком названий ровно в том виде, в каком они перечислены ниже.

        `departments` — отбор по структуре компании: «продажи оптового отдела»
        означает всех его продавцов вместе с подчинёнными отделами. Это не склад
        и не канал: склад — место, отдел — люди.

        {$this->filtersForPrompt()}

        # Что обязательно знать об этих цифрах

        {$this->lines($caveats)}
        TEXT;
    }

    /**
     * Справочник отбора — тем, что модели действительно нужно.
     *
     * Полный справочник весит четырнадцать тысяч знаков и съедал две трети
     * подсказки, то есть две трети расхода на **каждый** вопрос. Урезан он
     * дважды, и оба раза не наугад.
     *
     * Выручка у каждого значения выброшена: она здесь ради интерфейса — чтобы
     * крупные склады стояли в списке выше мелких, — а модели от неё нет
     * никакой пользы. Одна эта правка снимает больше половины веса.
     *
     * Менеджеры выброшены списком: их сто семьдесят восемь, и это сам по себе
     * самый длинный кусок подсказки. Модели они не нужны: вопрос о конкретном
     * человеке честнее закрывается раскладкой по разрезу `manager`, где он
     * виден вместе с соседями, чем отбором по одному имени, которое модель
     * всё равно угадывает по созвучию. Число оставлено — чтобы она понимала
     * порядок величин и не предлагала рейтинг на двести строк.
     *
     * Склады, каналы и сегменты остаются целиком: их шесть десятков на всех,
     * а отбор «по магазину Центральный» без точного названия не работает.
     */
    private function filtersForPrompt(): string
    {
        $values = $this->filters();

        if (($values['unavailable'] ?? false) === true) {
            return 'Сейчас недоступны — сервер аналитики не ответил. Не отбирай ни по складам, ни по каналам: '
                .'названий ты не знаешь, а выдуманное даст пустую панель.';
        }

        $trimmed = [
            'channels' => self::names($values['channels'] ?? []),
            'warehouses' => self::names($values['warehouses'] ?? []),
            'segments' => self::names($values['segments'] ?? []),
            // Отделы — из структуры компании, а не из витрины: «оптовый отдел»
            // живёт у нас, а не в 1С.
            'departments' => $this->structure->departmentNames(),
            'freshness' => $values['freshness'] ?? [],
        ];

        $managers = count(self::names($values['managers'] ?? []));

        return (string) json_encode($trimmed, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES)
            ."\n\nМенеджеров {$managers}, и списком они не переданы намеренно. Отбирать по одному имени не нужно: "
            .'на вопрос о конкретном человеке отвечай раскладкой по разрезу `manager` — в ней он виден вместе с соседями.';
    }

    /**
     * Имена значений без выручки за ними.
     *
     * @return list<string>
     */
    private static function names(mixed $values): array
    {
        if (! is_array($values)) {
            return [];
        }

        return array_values(array_filter(array_map(
            static fn (mixed $one): string => is_array($one) ? (string) ($one['value'] ?? '') : (string) $one,
            $values,
        ), static fn (string $one): bool => $one !== ''));
    }

    /**
     * @param  list<string>  $lines
     */
    private function lines(array $lines): string
    {
        return implode("\n", $lines);
    }
}
