<?php

declare(strict_types=1);

namespace App\Support\Chat;

/**
 * Чем можно откликнуться на реплику.
 *
 * Набор закрытый, и это не скупость. Открытый список означает, что под
 * сообщением руководителя однажды окажется знак, которого там быть не должно, а
 * убирать его придётся руками в базе. Двенадцати хватает на всё, ради чего
 * отклик и заводят: согласился, сделал, спорю, смешно.
 *
 * Список, а не таблица: он меняется раз в год, а читался бы на каждый щелчок.
 * Порядок здесь тот же, в каком знаки стоят в подсказке над сообщением, —
 * первым то, чем откликаются чаще всего.
 */
final readonly class Reactions
{
    /**
     * @var list<string>
     */
    public const ALLOWED = [
        '👍',
        '❤️',
        '🔥',
        '👏',
        '✅',
        '🙏',
        '😁',
        '🤔',
        '😢',
        '😮',
        '👎',
        '🤝',
    ];

    public static function allows(string $emoji): bool
    {
        return in_array($emoji, self::ALLOWED, strict: true);
    }
}
