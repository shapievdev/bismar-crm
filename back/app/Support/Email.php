<?php

declare(strict_types=1);

namespace App\Support;

/**
 * Почтовый адрес в том виде, в каком он хранится.
 *
 * Одно правило на всех, кто принимает почту: она необязательна, и пустое поле
 * значит «адреса нет», а не «адрес — пустая строка». Разница не косметическая:
 * пустую строку правило `email` забракует, а уникальный индекс пропустит только
 * одну такую на всю базу — второй сотрудник без почты уже не завёлся бы.
 */
final class Email
{
    /**
     * Приводит присланное к хранимому виду.
     *
     * Непонятное возвращается как есть: решать, что адрес неверен, — дело
     * проверки, а не этого места.
     */
    public static function normalize(mixed $value): mixed
    {
        if (! is_string($value)) {
            return $value;
        }

        $value = trim($value);

        return $value === '' ? null : $value;
    }
}
