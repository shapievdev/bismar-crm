<?php

declare(strict_types=1);

namespace App\Support;

/**
 * Российский номер телефона в том единственном виде, в каком он хранится.
 *
 * Одно правило на всех, кто принимает номер: приложение приводит присланное к
 * «+79990009977» само, а проверка потом лишь убеждается, что получилось именно
 * оно. Иначе один и тот же номер лежал бы в базе четырьмя записями — со
 * скобками, через восьмёрку, с дефисами и без, — и не совпал бы сам с собой.
 */
final class Phone
{
    /**
     * Ровно то, что должно лежать в столбце: плюс, семёрка и десять цифр.
     */
    public const PATTERN = '/^\+7\d{10}$/';

    /**
     * Приводит присланное к хранимому виду.
     *
     * Понимает всё, чем номер набирают вручную: «8 (999) 000-99-77»,
     * «+7 999 000 99 77», «9990009977». Пустое остаётся пустым — поле
     * необязательное. Непонятное возвращается как есть: решать, что номер
     * неверен, — дело проверки, а не этого места, иначе человек увидел бы
     * «поле обязательно» вместо «номер набран неправильно».
     */
    public static function normalize(?string $value): ?string
    {
        $value = trim((string) $value);

        if ($value === '') {
            return null;
        }

        $digits = preg_replace('/\D+/', '', $value) ?? '';

        // Одиннадцать цифр с восьмёркой или семёркой впереди — тот же номер,
        // набранный по-разному; десять — он же без кода страны.
        $national = match (true) {
            strlen($digits) === 11 && ($digits[0] === '8' || $digits[0] === '7') => substr($digits, 1),
            strlen($digits) === 10 => $digits,
            default => null,
        };

        return $national === null ? $value : '+7'.$national;
    }
}
