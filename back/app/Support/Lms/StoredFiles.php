<?php

declare(strict_types=1);

namespace App\Support\Lms;

use Illuminate\Support\Facades\Log;
use Illuminate\Support\Facades\Storage;
use Throwable;

/**
 * Уборка файлов, которые больше не нужны.
 *
 * Отдельно от загрузки, потому что отвечает за другое. Загрузка обязана
 * прогреметь: не сохранился файл — записи о нём быть не должно, диск на то и
 * настроен бросать исключения. А уборка вытесненного файла происходит после
 * того, как дело уже сделано, и её неудача ничего из сделанного не отменяет.
 *
 * Раньше она шла тем же способом, и недоступное хранилище превращало удачную
 * замену аватарки в ошибку на пустом месте: новый файл лежит, запись обновлена,
 * а сотруднику показывают пятисотую — из-за того, что не удалось стереть
 * старый. Осиротевший объект дешевле: его подметёт правило жизненного цикла
 * бакета, а до тех пор он никому не мешает.
 */
final class StoredFiles
{
    public static function discard(string $disk, ?string $path): void
    {
        if ($path === null || $path === '') {
            return;
        }

        try {
            Storage::disk($disk)->delete($path);
        } catch (Throwable $exception) {
            Log::warning('Вытесненный файл не удалён из хранилища.', [
                'disk' => $disk,
                'path' => $path,
                'exception' => $exception,
            ]);
        }
    }
}
