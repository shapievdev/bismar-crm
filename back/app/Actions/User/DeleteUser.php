<?php

declare(strict_types=1);

namespace App\Actions\User;

use App\Enums\AccessLevel;
use App\Exceptions\ConflictException;
use App\Models\User;
use Illuminate\Support\Facades\DB;

/**
 * Удаление учётной записи.
 *
 * Крайняя мера, а не будничная: обыкновенный уход из компании — это увольнение
 * (ChangeEmployment), после которого человек остаётся подписан под тем, что
 * написал. Удаляют, когда записи не должно быть видно вовсе, — заведённой по
 * ошибке или той, что просят убрать.
 *
 * **Удаление мягкое.** Строка остаётся в базе со всем, что за ней числится:
 * прогрессом обучения, попытками тестов, планом, допусками, авторством курсов и
 * сообщениями в переписках. Приложение её при этом не показывает нигде —
 * глобальный фильтр мягкого удаления снимает удалённого со всех запросов
 * разом, — и отчёт о движении персонала тоже: удалили, значит человека в
 * отчёте нет (решение пользователя 2026-10-22, см. App\Support\Staff\StaffReport,
 * где сказано, чем это оплачено).
 *
 * Мягкое оно, стало быть, не ради отчёта, а ради отмены: удалить не того
 * человека так же просто, как уволить не того, и единственное, чего мягкость
 * здесь стоит, — запись, которую не видно, но можно вернуть (RestoreUser).
 *
 * Отсюда и то, чего здесь нет: файлы не убираются, строки не уносятся каскадом,
 * ссылки не обнуляются. Уборка за удалением отменила бы только само удаление,
 * но не последствия.
 *
 * Телефон и почта при этом освобождаются сами: уникальность в базе спрашивается
 * у живых записей, — иначе номер, с которого входят, навсегда остался бы за
 * удалённой записью (см. миграцию
 * 2026_10_22_120000_let_a_deleted_employee_be_put_aside_rather_than_erased).
 */
final readonly class DeleteUser
{
    public function __construct(private RevokeOAuthTokens $revokeTokens) {}

    /**
     * @throws ConflictException
     */
    public function handle(User $user, User $actor): void
    {
        $this->ensureMayBeDeleted($user, $actor);

        DB::transaction(function () use ($user, $actor): void {
            // Сессии на учётную запись ключом не завязаны — иначе строка
            // осталась бы висеть с номером, за которым уже никого нет. Удалять
            // их всё равно надо: `auth:sanctum` удалённого не найдёт и сочтёт
            // гостем, но строка сессии дожила бы до своего срока сама.
            if (config('session.driver') === 'database') {
                DB::table(config('session.table', 'sessions'))
                    ->where('user_id', $user->getKey())
                    ->delete();
            }

            // Токены коннектора гасятся и здесь, хотя удаляют только
            // уволенного, у которого они погашены увольнением: удалённого
            // провайдер по токену больше не найдёт, но живая строка токена у
            // записи, которой для приложения нет, — это мусор, который однажды
            // прочитают.
            $this->revokeTokens->handle($user);

            // Через запись, а не `delete()` с последующим сохранением: у
            // удалённой модели сохранять уже нечего — её не видит и собственный
            // запрос на обновление.
            $user->forceFill(['deleted_by_id' => $actor->getKey()])->save();

            $user->delete();
        });
    }

    /**
     * Кого и кому позволено удалять.
     *
     * Только суперадминистратору и только уволенного: увольнение — обязательный
     * первый шаг, и не ради обряда. Оно обрывает сессии, закрывает вход и даёт
     * время передумать, а заодно держит удалённых внутри уволенных — на этом
     * стоят все прочие отчёты приложения, которые ушедших не считают.
     *
     * Проверка живёт здесь, а не в политике: Gate::before пропускает
     * администраторов не глядя, и политика бы не спросилась.
     *
     * @throws ConflictException
     */
    private function ensureMayBeDeleted(User $user, User $actor): void
    {
        if ($actor->accessLevel() !== AccessLevel::SuperAdmin) {
            throw new ConflictException('Удалять учётные записи может только суперадминистратор.');
        }

        if ($user->is($actor)) {
            throw new ConflictException('Нельзя удалить самого себя.');
        }

        if (! $user->isDismissed()) {
            throw new ConflictException('Удалить можно только уволенного сотрудника — сначала увольте его.');
        }
    }
}
