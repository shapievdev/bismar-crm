<?php

declare(strict_types=1);

namespace App\Actions\User;

use App\Models\User;
use Laravel\Passport\Passport;

/**
 * Гасит токены коннектора, выданные этому человеку.
 *
 * Зовут отсюда двое — увольнение и удаление записи, — и оба по той же причине,
 * по какой они обрывают сессии: сессия не единственный ключ от двери. Токен
 * OAuth живёт сутки и лежит на чужом сервере, так что уволенный, у которого
 * коннектор подключён, продолжал бы работать в платформе через claude.ai —
 * `EnsureEmployed` отвечал бы ему отказом, но держать открытую дверь в расчёте
 * на вахтёра неправильно.
 *
 * Гасятся и обновляющие токены, иначе коннектор немедленно выменял бы погашенный
 * на свежий: refresh живёт тридцать дней и спрашивает только себя.
 *
 * Не удаляются, а помечаются погашенными — так это делает и сам Passport
 * (Token::revoke). Строка остаётся свидетельством: по ней видно, что доступ был
 * и когда закончился. Прибирает их `passport:purge`.
 *
 * Отдельным действием, а не строкой в каждом из двух, потому что правило одно, и
 * третьему случаю (смена пароля, например) оно понадобится целиком.
 */
final readonly class RevokeOAuthTokens
{
    /**
     * @return int сколько токенов погасили — для журнала и для тестов
     */
    public function handle(User $user): int
    {
        // Напрямую по модели, а не через связь `tokens()`: та сужает выборку
        // клиентами своего провайдера, а здесь нужны все токены человека, кем
        // бы ни был заведён клиент.
        $tokens = Passport::token()->newQuery()->where('user_id', $user->getKey());

        $ids = $tokens->clone()->pluck('id')->all();

        if ($ids === []) {
            return 0;
        }

        Passport::refreshToken()->newQuery()
            ->whereIn('access_token_id', $ids)
            ->update(['revoked' => true]);

        return $tokens->update(['revoked' => true]);
    }
}
