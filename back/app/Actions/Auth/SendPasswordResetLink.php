<?php

declare(strict_types=1);

namespace App\Actions\Auth;

use App\Models\User;
use App\Notifications\ResetPasswordLink;
use App\Support\Phone;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Facades\Password;
use Throwable;

/**
 * Выдать ссылку на смену забытого пароля.
 *
 * Наружу это действие не рассказывает ничего: ни «такого номера нет», ни «у
 * него не записана почта», ни «ссылку вы просили минуту назад». Ответ формы
 * один на все случаи — иначе она перебором рассказывала бы посторонним, кто в
 * компании работает, а это та же причина, по которой неизвестный номер и
 * неверный пароль на входе неотличимы (см. AttemptLogin).
 *
 * Разбираться, почему письмо не пришло, приходится администратору, и потому
 * причина пишется в журнал приложения — единственное место, где она есть.
 *
 * Спрашивается телефон **или** почта. Входят в платформу по номеру, и его
 * человек помнит; записана ли у него почта — обычно нет. Заставить его угадать
 * поле значило бы отказать половине просящих молча.
 */
final readonly class SendPasswordResetLink
{
    public function handle(string $login): void
    {
        $person = $this->person($login);

        if (! $person instanceof User) {
            Log::info('Смена пароля: по «'.$login.'» никого не нашли.');

            return;
        }

        // Писать некуда. Это не редкость: почта в платформе необязательна —
        // логин телефон, — и таким сотрудникам пароль по-прежнему ставит
        // администратор.
        if ($person->email === null || $person->email === '') {
            Log::info("Смена пароля: у сотрудника №{$person->getKey()} не записана почта.");

            return;
        }

        $tokens = Password::broker()->getRepository();

        // Вторую ссылку подряд не выдаём: предел стоит в config/auth.php и
        // защищает не нас, а владельца ящика — иначе чужими просьбами ему
        // завалили бы почту.
        if ($tokens->recentlyCreatedToken($person)) {
            Log::info("Смена пароля: сотруднику №{$person->getKey()} ссылка выдана только что.");

            return;
        }

        /*
         * Почтовый сервер — чужой, и он бывает недоступен: Яндекс закрыл
         * соединение, кончился пароль приложения, упала сеть. Человеку в этот
         * момент нужен тот же ответ, что и всегда: иначе форма смены пароля
         * отвечала бы пятисотой, и он решил бы, что сломалась платформа.
         *
         * Отказ при этом не проглатывается, а уходит в `report()` — туда же,
         * куда все исключения приложения: молча неработающая почта хуже
         * видимой ошибки. Токен остаётся выданным; в худшем случае человек
         * попросит ссылку заново через минуту.
         */
        try {
            $person->notify(new ResetPasswordLink($tokens->create($person)));
        } catch (Throwable $failure) {
            report($failure);

            Log::warning("Смена пароля: письмо сотруднику №{$person->getKey()} не ушло — {$failure->getMessage()}");

            return;
        }

        Log::info("Смена пароля: сотруднику №{$person->getKey()} отправлена ссылка.");
    }

    /**
     * Кому это принадлежит — работающему сотруднику.
     *
     * Уволенного здесь нет намеренно: войти он всё равно не может, и ссылка
     * привела бы его к форме, за которой отказ. Удалённого не видно и так —
     * мягкое удаление снимает его со всех запросов.
     */
    private function person(string $login): ?User
    {
        $login = trim($login);
        $phone = Phone::normalize($login);

        if ($phone !== null && preg_match(Phone::PATTERN, $phone) === 1) {
            return User::query()->employed()->where('phone', $phone)->first();
        }

        /*
         * Почта сравнивается без учёта регистра, хотя хранится как набрана:
         * базы живут в коллации C, и «Ivanov@bismar.pro» не совпал бы с тем,
         * что человек набрал строчными. Совпади при этом сразу две записи —
         * не выбираем наугад: письмо ушло бы, возможно, не тому.
         */
        $matches = User::query()
            ->employed()
            ->whereRaw('lower(email) = lower(?)', [$login])
            ->limit(2)
            ->get();

        if ($matches->count() !== 1) {
            return null;
        }

        return $matches->first();
    }
}
