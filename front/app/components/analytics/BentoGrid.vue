<script setup lang="ts">
/**
 * Сетка дашборда.
 *
 * Двенадцать колонок и ряд постоянной высоты — вместо `auto-fit` с минимальной
 * шириной, которым панели раскладывались раньше. Разница не косметическая:
 * `auto-fit` отдаёт каждой панели одинаковую долю ширины и ровно столько
 * высоты, сколько попросило её содержимое, поэтому график на четыре точки и
 * график на девяносто получали один размер, а нижние края карточек вставали
 * вразнобой. Панель здесь сама объявляет, сколько места занимает, и главному
 * графику достаётся втрое больше, чем подписи рядом с ним.
 *
 * Плитки со сводными числами лежат в этой же сетке, а не в своей строке над
 * ней: два соседних грида с разным шагом — это два ритма на одном экране, и
 * именно они читаются как разбросанность.
 *
 * Высота ряда задана в единицах, а не подогнана под содержимое: нижние края
 * панелей одного ряда обязаны совпадать, иначе сетка перестаёт быть сеткой.
 * Верхняя граница ряда всё же `auto` — длинное пояснение в шапке карточки
 * должно раздвинуть ряд, а не оказаться обрезанным.
 */
</script>

<template>
  <div class="bento">
    <slot />
  </div>
</template>

<style scoped>
.bento {
  /* Зазор объявлен переменной, а не числом: панель с прокруткой считает по нему
     свой предел высоты, и разъехавшись, эти два значения разложили бы ряд. */
  --bento-gap: 0.9rem;

  display: grid;
  grid-template-columns: repeat(12, minmax(0, 1fr));
  grid-auto-rows: minmax(var(--bento-row, 10.5rem), auto);
  gap: var(--bento-gap);
  align-items: stretch;
}

/*
 * Планшет: колонок вдвое меньше, и панели раскладываются по ним сами — правило
 * пересчёта живёт в самих панелях, потому что только они знают свою ширину.
 */
@media (max-width: 68rem) {
  .bento {
    grid-template-columns: repeat(6, minmax(0, 1fr));
  }
}

/*
 * Телефон: две колонки. Сводные плитки встают парами — по одной в строке они
 * растянули бы страницу настолько, что до графиков пришлось бы прокручивать
 * половину экрана.
 */
@media (max-width: 40rem) {
  .bento {
    grid-template-columns: repeat(2, minmax(0, 1fr));
    grid-auto-rows: minmax(var(--bento-row-narrow, 8rem), auto);
    gap: 0.6rem;
  }
}
</style>