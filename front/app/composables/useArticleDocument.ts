import type { JSONContent } from '@tiptap/core'
import type { LessonAttachment } from '~/types/lms'
import { withResolvedMedia, withoutResolvedMedia } from '~/utils/editor/attachments'
import { isSameDocument } from '~/utils/editor/document'

/** Что редактору статьи нужно знать о перечитанной записи. */
interface Article {
  content: JSONContent | null
  attachments: LessonAttachment[]
}

/**
 * Статья в редакторе, которую не затирает перечитанная запись.
 *
 * Запись перечитывается далеко не только после сохранения: загрузили картинку в
 * текст, удалили файл, сохранили список ответственных, завели проверку. Каждый
 * раз статья возвращалась к последней сохранённой, унося написанное прямо
 * сейчас — абзац, вставленный HTML-блок, вставленное видео. Ошибка тихая и
 * обиднее многих: ничего не мигнуло, текст просто исчез.
 *
 * Поэтому при несохранённых правках остаётся написанное автором, а обновляются
 * в нём только адреса вложений — ради них перечитывание и затевалось, подпись у
 * них живёт минуты. Когда правок нет, статья берётся с сервера: там ей могли
 * проставить имена блоков, на которые ссылается таблица урока.
 *
 * @param source  Сама запись — урок, документ, новость.
 * @param read    Где у неё статья и список вложений.
 */
export function useArticleDocument<T>(
  source: MaybeRefOrGetter<T | null | undefined>,
  read: (record: T) => Article,
) {
  // Мелкая ссылка, а не глубокая: документ всегда подменяется целиком, и
  // оборачивать в реактивный прокси всё дерево статьи на каждое нажатие
  // клавиши незачем.
  const document = shallowRef<JSONContent | null>(null)

  /**
   * Подставляли ли статью хоть раз.
   *
   * До первой подстановки сравнивать не с чем: пустой редактор расходится с
   * любой записью. Без этой оговорки правки «находились» бы там, где автор ещё
   * ничего не трогал, — и статья, принятая за авторскую, так и осталась бы
   * пустой.
   *
   * Ссылка, а не обычная переменная: на ней стоит ранний выход из `isDirty`, и
   * невидимая для реактивности она навсегда оставляла бы вычисляемое значение с
   * тем набором зависимостей, что был на первом проходе, — то есть без самой
   * статьи.
   */
  const hasSeeded = ref(false)

  /**
   * Расходится ли статья с тем, что лежит на сервере.
   *
   * Сравнивается не со слепком, снятым при загрузке, а с самой записью:
   * страница перечитывает её из полудюжины мест, и слепок пришлось бы обновлять
   * в каждом, не забыв ни одного. С этим сравнением состояние чинится само:
   * пришли свежие данные — расхождение пересчиталось.
   *
   * Адреса вложений в сравнении не участвуют: они подставляются на входе и
   * снимаются на выходе, а в записи хранятся одни номера.
   */
  const isDirty = computed(() => {
    const record = toValue(source)

    if (!record || !hasSeeded.value) {
      return false
    }

    return !isSameDocument(withoutResolvedMedia(document.value), read(record).content ?? null)
  })

  watch(() => toValue(source), (record) => {
    // Запись пропала — не повод очищать редактор: перечитывание могло и не
    // удаться, а статья на экране от этого не становится хуже.
    if (!record) {
      return
    }

    const article = read(record)

    document.value = isDirty.value
      ? withResolvedMedia(document.value, article.attachments)
      : withResolvedMedia(article.content, article.attachments)

    hasSeeded.value = true
  }, { immediate: true })

  /**
   * Забрать статью с сервера после сохранения — вместе с тем, что он в ней
   * поправил.
   *
   * Правит он немало: проставляет блокам имена, на которые ссылаются строки
   * таблицы ответов. Без этого шага редактор остался бы с безымянными блоками
   * до перезагрузки страницы, а «есть несохранённые правки» не погасло бы
   * никогда — расхождение-то настоящее.
   *
   * Забирается серверная версия только тогда, когда в редакторе всё ещё лежит
   * отправленное: пока запрос был в пути, автор мог дописать абзац, и накрыть
   * его сохранённым значило бы потерять текст ровно тем способом, от которого
   * здесь всё и защищает.
   *
   * @param sent  Статья ровно в том виде, в каком её отправили на сервер.
   */
  function adoptSaved(sent: JSONContent | null): void {
    const record = toValue(source)

    if (!record || !isSameDocument(withoutResolvedMedia(document.value), sent)) {
      return
    }

    const article = read(record)

    document.value = withResolvedMedia(article.content, article.attachments)
  }

  return { document, isDirty, adoptSaved }
}
