/**
 * Что страница просит убрать из оболочки вокруг себя.
 *
 * Пока такое требование одно: открытый разговор на телефоне забирает экран
 * целиком и просит убрать нижнюю полосу разделов. Так делают все мессенджеры, и
 * не ради красоты — полоса съедает те самые восемьдесят точек, которых не
 * хватает ленте, и ставит второй ряд кнопок вплотную под полем ввода: палец,
 * промахнувшись мимо «отправить», уходит в другой раздел.
 *
 * Через общее состояние, а не через `definePageMeta`: разговор открывают и
 * закрывают, не уходя со страницы, а мета у страницы одна на всё время, пока
 * она открыта.
 *
 * Прятать или нет, решает уже сама полоса — по ширине экрана. На планшете
 * мессенджер показывает обе панели сразу, и разделы там никуда не деваются.
 */
export function useShellChrome() {
  const hideDock = useState<boolean>('shell.hide-dock', () => false)

  /**
   * Возвращает оболочку как было.
   *
   * Зовётся при уходе со страницы: состояние общее и переживает её, а полоса
   * разделов, не вернувшаяся на место, оставила бы человека без навигации.
   */
  function restoreChrome(): void {
    hideDock.value = false
  }

  return { hideDock, restoreChrome }
}
