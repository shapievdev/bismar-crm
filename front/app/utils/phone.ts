/**
 * Телефон сотрудника.
 *
 * В базе он лежит одним видом — «+79990009977», — а человеку и в поле ввода, и
 * в списке показывается разбитым на части: «+7 (999) 000-99-77». Разделители
 * рисует маска и она же их снимает, поэтому набранное вручную и вставленное из
 * буфера доходят до сервера одинаковыми.
 *
 * Сервер приводит присланное к тому же виду сам (App\Support\Phone) — здесь
 * это ради удобства набора, а не вместо проверки.
 */

/** Длина российского номера без кода страны. */
const NATIONAL_LENGTH = 10

/**
 * Десять цифр номера — всё, что от набранного важно.
 *
 * Код страны снимается в два приёма, и оба нужны.
 *
 * Сначала — «+7», написанное самой маской: эта семёрка не цифра номера, и
 * считать её цифрой значит переписывать номер на каждом нажатии — набранное
 * «+7 (9» превращалось в «+7 (79». Ищется она по плюсу и где угодно в строке,
 * а не только в начале: курсор можно поставить перед плюсом и набирать оттуда.
 *
 * Потом — код, набранный человеком: восьмёрка впереди снимается всегда (с неё
 * начинают набор, но не сам номер), а семёрка — только когда цифр больше
 * десяти, иначе у номера, который и правда начинается на семь, отняли бы
 * первую.
 */
function nationalDigits(value: string): string {
  let digits = value.replace(/\+\s*7/, ' ').replace(/\D+/g, '')

  if (digits.startsWith('8')) {
    digits = digits.slice(1)
  }
  else if (digits.length > NATIONAL_LENGTH && digits.startsWith('7')) {
    digits = digits.slice(1)
  }

  return digits.slice(0, NATIONAL_LENGTH)
}

/**
 * Вид для поля ввода и для чтения — по мере набора, а не только целиком:
 * «+7 (999» на середине номера тоже читается.
 *
 * Пустое остаётся пустым: поле необязательное, и стерев номер человек должен
 * увидеть пустоту, а не «+7 (».
 */
export function maskPhone(value: string): string {
  const digits = nationalDigits(value)

  if (digits === '') {
    return ''
  }

  return [
    `+7 (${digits.slice(0, 3)}`,
    digits.length > 3 ? `) ${digits.slice(3, 6)}` : '',
    digits.length > 6 ? `-${digits.slice(6, 8)}` : '',
    digits.length > 8 ? `-${digits.slice(8, 10)}` : '',
  ].join('')
}

/**
 * То, что уходит на сервер: «+79990009977» или ничего.
 *
 * Недобранный номер уходит тоже — коротким: пусть о нём скажет проверка на
 * сервере, а не молчаливое обнуление, из-за которого набранное исчезло бы.
 */
export function phoneForApi(value: string): string | null {
  const digits = nationalDigits(value)

  return digits === '' ? null : `+7${digits}`
}
