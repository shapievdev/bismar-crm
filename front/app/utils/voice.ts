/**
 * Общие числа голосового сообщения — те же, что у сервера.
 *
 * Здесь, а не в самих компонентах: запись, показ и подрезка на сервере обязаны
 * думать об одном и том же числе столбиков, иначе присланная волна не совпадёт
 * с нарисованной.
 */

/** Сколько столбиков рисует волна. Столько же принимает сервер. */
export const VOICE_BARS = 56

/** Дольше пяти минут — это уже не реплика, а запись совещания. */
export const VOICE_MAX_SECONDS = 300

/**
 * Достраивает волну до полной ширины.
 *
 * Короткая запись даёт пять столбиков на всю ширину пузыря, и пять толстых
 * полос не читаются как звук. Недостающее добивается тишиной, а сама волна
 * прижимается влево — как она и звучала.
 */
export function paddedWaveform(waveform: number[]): number[] {
  if (waveform.length === 0) {
    // Волны нет вовсе — рисуем ровную полосу: это всё-таки запись, а не файл.
    return Array.from({ length: VOICE_BARS }, () => 12)
  }

  if (waveform.length >= VOICE_BARS) {
    return waveform.slice(0, VOICE_BARS)
  }

  return [...waveform, ...Array.from({ length: VOICE_BARS - waveform.length }, () => 0)]
}
