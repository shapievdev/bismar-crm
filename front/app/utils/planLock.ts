/**
 * Отказ «сначала пройдите план обучения» — как его читать на экране.
 *
 * Курс, до которого не дошла очередь плана, отвечает 403 и объясняет отказ
 * словами: сервер один знает, на каком шаге стоит этот человек. Экранам
 * остаётся не подменить это объяснение своим — страница курса на любую ошибку
 * отвечала «не найдено», а закрытый курс существует и человеку виден.
 */

/** Сообщение сервера, если он отказал именно из-за плана. Иначе — ничего. */
export function planLockMessage(error: unknown): string | null {
  const failure = error as { statusCode?: number, data?: { message?: string } } | null

  if (failure?.statusCode !== 403) {
    return null
  }

  return failure.data?.message ?? 'Материал откроется, когда вы завершите план обучения.'
}
