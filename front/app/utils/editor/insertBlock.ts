import type { Command, JSONContent } from '@tiptap/core'

/**
 * Вставляет блок в статью и уводит курсор за него.
 *
 * Без этого вставленный блок остаётся выделенным целиком — не курсор в тексте,
 * а выделение узла, — и следующее же действие встаёт на его место. Так и
 * пропадала свежая разметка: автор заводил HTML-блок и тут же добавлял видео, а
 * видео вставало вместо блока. Тем же способом блок стирала любая набранная
 * буква.
 *
 * Пустой абзац следом ставится нарочно и всегда. Блоки здесь неделимые
 * (`atom`), и стоящий последним не оставлял бы места, куда писать дальше:
 * добравшись до конца статьи, автор упирался в картинку и не мог продолжить.
 *
 * @param node  Узел документа — блок HTML, видео, картинка, файл с Диска.
 */
export function insertBlock(node: JSONContent): Command {
  return ({ chain }) => chain().insertContent([node, { type: 'paragraph' }]).run()
}
