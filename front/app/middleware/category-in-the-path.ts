/**
 * Прежний адрес категории: `?category=kassa` → `/category/kassa`.
 *
 * Категория в каталоге переехала из запроса в адрес (решение пользователя
 * 2026-09-30), а ссылки прежнего вида лежат у людей в закладках, в истории
 * браузера и в отправленных сообщениях. Переводим их сами — молча открывать
 * корень значило бы терять место, к которому вела ссылка.
 *
 * Посредником, а не `routeRules`: правила маршрутов сопоставляют путь и запроса
 * не видят, а перевод нужен именно по нему. Стоит он на корнях трёх каталогов
 * (`/lms`, `/lms/documents`, `/lms/handbooks`) — только им такой запрос и
 * приходил, — и путь собирает из текущего, поэтому четвёртый каталог
 * подключится строкой в `definePageMeta`, а не правкой этого файла.
 *
 * Остальной запрос едет с собой: поиск и вкладка — уточнения к списку, и
 * ссылка на «черновики в этой категории» обязана открыть именно их.
 */
export default defineNuxtRouteMiddleware((to) => {
  const slug = typeof to.query.category === 'string' ? to.query.category.trim() : ''

  if (slug === '') {
    return
  }

  const query = { ...to.query }

  delete query.category

  return navigateTo(
    { path: `${to.path.replace(/\/$/, '')}/category/${slug}`, query },
    { replace: true, redirectCode: 301 },
  )
})
